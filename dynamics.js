  function arrow(ctx, from, to, color, width, head) {
    const dx = to.x - from.x, dy = to.y - from.y;
    const L = Math.hypot(dx, dy);
    if (L < 0.5) return;
    const ux = dx / L, uy = dy / L;
    const hl = head == null ? Math.min(11, L * 0.35) : head;
    ctx.strokeStyle = color; ctx.fillStyle = color;
    ctx.lineWidth = width || 2.5; ctx.lineCap = "round";
    ctx.beginPath();
    ctx.moveTo(from.x, from.y);
    ctx.lineTo(to.x - ux * hl * 0.85, to.y - uy * hl * 0.85);
    ctx.stroke();
    ctx.beginPath();
    ctx.moveTo(to.x, to.y);
    ctx.lineTo(to.x - ux * hl - uy * hl * 0.42, to.y - uy * hl + ux * hl * 0.42);
    ctx.lineTo(to.x - ux * hl + uy * hl * 0.42, to.y - uy * hl - ux * hl * 0.42);
    ctx.closePath(); ctx.fill();
  }

  // A curved arrow, for moments. sign > 0 draws counter-clockwise.
  function momentArc(ctx, c, r, sign, color, lw) {
    if (Math.abs(sign) < 1e-9) return;
    const dir = sign > 0 ? -1 : 1;           // canvas y is down, so flip
    ctx.strokeStyle = color; ctx.fillStyle = color; ctx.lineWidth = lw || 2.4;
    ctx.beginPath();
    ctx.arc(c.x, c.y, r, dir > 0 ? -2.5 : 0.6, dir > 0 ? 0.6 : -2.5, dir < 0);
    ctx.stroke();
    const a = dir > 0 ? 0.6 : -2.5;
    const tipP = { x: c.x + r * Math.cos(a), y: c.y + r * Math.sin(a) };
    const tang = { x: -Math.sin(a) * dir, y: Math.cos(a) * dir };
    arrow(ctx, { x: tipP.x - tang.x * 8, y: tipP.y - tang.y * 8 }, tipP, color, lw || 2.4, 8);
  }

