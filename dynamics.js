  const sub = (a, b) => ({ x: a.x - b.x, y: a.y - b.y });
  const len = (a, b) => Math.hypot(a.x - b.x, a.y - b.y);
  const lerp = (a, b, t) => ({ x: a.x + (b.x - a.x) * t, y: a.y + (b.y - a.y) * t });
  // 2-D cross product, z component: the moment of F applied at r about the origin.
  const cross = (r, F) => r.x * F.y - r.y * F.x;

  // Build the three segments, proximal joint last-solved-first order: foot, shank, thigh.
  function segments() {
    const P = segParams(), M = STATE.mass;
    const Lfoot = len(STATE.heel, STATE.toe);
    const Lshank = len(STATE.knee, STATE.ankle);
    const Lthigh = len(STATE.hip, STATE.knee);
    const mk = (key, L, a, b, joint, mass, comFrac, rg) => {
      const m = mass * M;
      return {
        key, L, m,
        I: m * Math.pow(rg * L, 2),
        com: lerp(a, b, comFrac),
        prox: joint,
        a: STATE.acc[key],
        alpha: STATE.alpha[key],
      };
    };
    return [
      // foot: inertial axis heel -> toe, but the joint is the ankle
      mk("foot", Lfoot, STATE.heel, STATE.toe, STATE.ankle, P.foot.mass, P.foot.com, P.foot.rg),
      mk("shank", Lshank, STATE.knee, STATE.ankle, STATE.knee, P.shank.mass, P.shank.com, P.shank.rg),
      mk("thigh", Lthigh, STATE.hip, STATE.knee, STATE.hip, P.thigh.mass, P.thigh.com, P.thigh.rg),
    ];
  }

  // The recursion. Start at the ground and climb.
  //   Newton:  F_prox = m·a − F_dist − m·g        (g = (0, −G), so −m·g = (0, +mG))
  //   Euler:   M_prox = I·α − M_dist − (r_prox × F_prox) − (r_dist × F_dist)
  // The ground applies NO moment at the centre of pressure. That is the definition of
  // the centre of pressure, and it is the only reason the chain has a starting point.
  function solve() {
    const segs = segments();
    const distalPointOf = ["cop", "ankle", "knee"];
    let Fdist = { x: STATE.grf.x, y: STATE.grf.y };
    let Mdist = 0;
    let dPoint = STATE.cop;
    const out = [];

    segs.forEach((s, i) => {
      const a = STATE.useInertia ? s.a : { x: 0, y: 0 };
      const al = STATE.useInertia ? s.alpha : 0;

      const Fp = {
        x: s.m * a.x - Fdist.x,
        y: s.m * a.y - Fdist.y + s.m * G,
      };
      const rp = sub(s.prox, s.com);
      const rd = sub(dPoint, s.com);
      const termP = cross(rp, Fp);
      const termD = cross(rd, Fdist);
      const inertial = s.I * al;
      const Mp = inertial - Mdist - termP - termD;

      out.push({
        seg: s, Fp, Mp, rp, rd, termP, termD, inertial,
        Fdist: { x: Fdist.x, y: Fdist.y }, Mdist, dPoint,
        weight: s.m * G,
        distalName: distalPointOf[i],
      });

      // Newton's third law hands the answer to the next segment up.
      Fdist = { x: -Fp.x, y: -Fp.y };
      Mdist = -Mp;
      dPoint = s.prox;
    });
    return out;
  }

